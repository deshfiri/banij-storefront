const dictionaries: Record<Locale, Dictionary> = { en, bn };

export function dictionary(locale: Locale): Dictionary {
  return dictionaries[locale];
}

/** A language's own name, written in that language (used on language switches). */
export function languageName(locale: string): string {
  return locale === "bn" ? "বাংলা" : "English";
}

export function fill(template: string, values: Record<string, string | number>): string {
  return template.replace(/\{(\w+)\}/g, (_, key: string) => String(values[key] ?? ""));
}

export function statusLabel(t: Dictionary, status: string): string {
  return (t.status as Record<string, string>)[status] ?? t.status.unknown;
}
